const ALL: Record<Lang, Dict> = { ko, en, ja, zh, es, fr, de, pt, vi, id };

export type TFn = (key: string, vars?: Record<string, string | number>) => string;

/** Look up a key with fallback lang → en → ko → key itself. */
export function tx(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const table = ALL[lang] ?? {};
  let s = table[key] ?? en[key] ?? ko[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function makeT(lang: Lang): TFn {
  return (key, vars) => tx(lang, key, vars);
}

export function isLang(v: string | null): v is Lang {
  return (LANGS as { code: string }[]).some((l) => l.code === v);
}
