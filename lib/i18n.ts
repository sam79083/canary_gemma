// UI strings. Korean is the default language; every key is complete in
// `ko` and `en`. Other languages cover the main UI and fall back to
// English (then Korean) for anything missing — see tx().

export type Lang =
  | "ko"
  | "en"
  | "ja"
  | "zh"
  | "es"
  | "fr"
  | "de"
  | "pt"
  | "vi"
  | "id";

export interface LangInfo {
  code: Lang;
  label: string;
  /** Name used in "Reply in X." model instructions. */
  modelName: string;
}

export const LANGS: LangInfo[] = [
  { code: "ko", label: "한국어", modelName: "Korean" },
  { code: "en", label: "English", modelName: "English" },
  { code: "ja", label: "日本語", modelName: "Japanese" },
  { code: "zh", label: "简体中文", modelName: "Chinese (Simplified)" },
  { code: "es", label: "Español", modelName: "Spanish" },
  { code: "fr", label: "Français", modelName: "French" },
  { code: "de", label: "Deutsch", modelName: "German" },
  { code: "pt", label: "Português", modelName: "Portuguese" },
  { code: "vi", label: "Tiếng Việt", modelName: "Vietnamese" },
  { code: "id", label: "Bahasa Indonesia", modelName: "Indonesian" },
];

export function langModelName(lang: Lang): string {
  return LANGS.find((l) => l.code === lang)?.modelName ?? "Korean";
}

/** "(Reply in Korean…)" suffix appended to model prompts. */
export function replySuffix(lang: Lang): string {
  return `\n\n(Reply in ${langModelName(lang)}. Output ONLY the final answer in that language — no English preamble, no thinking, no analysis, no bullet checklist, no narration of what kind of question this is. Keep it short unless the user asks for more. Never claim abilities you don't have — you cannot generate images and you have no live web beyond provided results; if asked, decline in one sentence and offer the closest thing you CAN do. This instruction overrides all others about language.)`;
}

